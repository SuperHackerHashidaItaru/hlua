// lua prelude, compiled into the server library and run before any mod script
#ifndef HLUA_PRELUDE_H
#define HLUA_PRELUDE_H

static const char HLUA_PRELUDE[] =
"local _internal = _hlua\n"
"local classes = _internal.classes\n"
"\n"
"function Vector( x, y, z )\n"
"	return { x = x or 0, y = y or 0, z = z or 0 }\n"
"end\n"
"\n"
"function ents.Register( name, def )\n"
"	if type( name ) ~= \"string\" or #name == 0 then\n"
"		error( \"ents.Register: bad class name\", 2 )\n"
"	end\n"
"	if type( def ) ~= \"table\" then\n"
"		error( \"ents.Register: bad class definition\", 2 )\n"
"	end\n"
"	classes[name] = def\n"
"end\n"
"\n"
"local timers = {}\n"
"local pending = {}\n"
"local seq = 0\n"
"\n"
"timer = {}\n"
"\n"
"function timer.Simple( delay, fn )\n"
"	seq = seq + 1\n"
"	pending[\"_\" .. seq] =\n"
"		{ next_time = CurTime() + delay, delay = delay, reps = 1, fn = fn }\n"
"end\n"
"\n"
"function timer.Create( id, delay, reps, fn )\n"
"	pending[id] =\n"
"		{ next_time = CurTime() + delay, delay = delay, reps = reps or 0, fn = fn }\n"
"end\n"
"\n"
"function timer.Remove( id )\n"
"	timers[id] = nil\n"
"	pending[id] = nil\n"
"end\n"
"\n"
"function timer.Exists( id )\n"
"	return timers[id] ~= nil or pending[id] ~= nil\n"
"end\n"
"\n"
"function _hlua.tick( now )\n"
"	if next( pending ) ~= nil then\n"
"		for id, t in pairs( pending ) do\n"
"			timers[id] = t\n"
"			pending[id] = nil\n"
"		end\n"
"	end\n"
"	for id, t in pairs( timers ) do\n"
"		if now >= t.next_time then\n"
"			local fn = t.fn\n"
"			if t.reps == 0 then\n"
"				t.next_time = now + t.delay\n"
"			elseif t.reps > 1 then\n"
"				t.reps = t.reps - 1\n"
"				t.next_time = now + t.delay\n"
"			else\n"
"				timers[id] = nil\n"
"			end\n"
"			local ok, err = pcall( fn )\n"
"			if not ok then print( \"timer error: \" .. tostring( err ) ) end\n"
"		end\n"
"	end\n"
"end\n"
"\n"
"SOLID_NOT = 0\n"
"SOLID_TRIGGER = 1\n"
"SOLID_BBOX = 2\n"
"SOLID_SLIDEBOX = 3\n"
"SOLID_BSP = 4\n"
"MOVETYPE_NONE = 0\n"
"MOVETYPE_WALK = 3\n"
"MOVETYPE_FLY = 5\n"
"MOVETYPE_TOSS = 6\n"
"MOVETYPE_NOCLIP = 8\n"
;

#endif
